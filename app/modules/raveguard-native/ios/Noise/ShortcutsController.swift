/// The two listening modes RaveGuard can request through Apple's Shortcuts app.
///
/// Adaptive remains the normal mode because the AirPods adjust their own blend of
/// Transparency and ANC. RaveGuard escalates to full ANC at the configured threshold.
enum NativeNoiseMode: String, Equatable, Sendable {
    case adaptive
    case noiseCancellation
}

enum ShortcutRequestPhase: Equatable, Sendable {
    case idle
    case scheduled(Date)
    case opening
    case launched
    case completed
    case cancelled
    case failed
}

/// State suitable for forwarding through the native module's future `onNoise` event.
struct ShortcutsControllerState: Equatable, Sendable {
    let level: Int
    let mode: NativeNoiseMode
    let phase: ShortcutRequestPhase
}

protocol ShortcutURLOpening: AnyObject {
    func open(_ url: URL, completion: @escaping (Bool) -> Void)
}

protocol NoiseScheduledAction: AnyObject {
    func cancel()
}

protocol NoiseDwellScheduling: AnyObject {
    var now: Date { get }

    @discardableResult
    func schedule(after delay: TimeInterval, _ action: @escaping () -> Void) -> NoiseScheduledAction
}

/// Maps RaveGuard's 0...100 protection value to native AirPods listening modes.
///
/// This does not use private AirPods APIs. It opens user-created Shortcuts which use
/// Apple's `Set Noise Control Mode` action, then returns through `raveguard://`.
/// Calls are coalesced behind a dwell so a noisy input signal cannot repeatedly bounce
/// the wearer between Adaptive and full Noise Cancellation.
final class ShortcutsController: NoiseController {
    struct Configuration: Equatable, Sendable {
        var ancThreshold = 70
        var dwell: TimeInterval = 25
        var adaptiveShortcutName = "RG Adaptive"
        var noiseCancellationShortcutName = "RG Noise Cancellation"
        var callbackScheme = "raveguard"

        init(
            ancThreshold: Int = 70,
            dwell: TimeInterval = 25,
            adaptiveShortcutName: String = "RG Adaptive",
            noiseCancellationShortcutName: String = "RG Noise Cancellation",
            callbackScheme: String = "raveguard"
        ) {
            self.ancThreshold = min(100, max(0, ancThreshold))
            self.dwell = max(0, dwell)
            self.adaptiveShortcutName = adaptiveShortcutName
            self.noiseCancellationShortcutName = noiseCancellationShortcutName
            self.callbackScheme = callbackScheme
        }
    }

    var onStateChange: ((ShortcutsControllerState) -> Void)?

    private let configuration: Configuration
    private let opener: ShortcutURLOpening
    private let scheduler: NoiseDwellScheduling

    private var desiredLevel = 0
    private var desiredMode: NativeNoiseMode = .adaptive
    private var lastLaunchedMode: NativeNoiseMode?
    private var lastCompletedMode: NativeNoiseMode?
    private var lastLaunchAt: Date?
    private var pendingAction: NoiseScheduledAction?
    private var pendingMode: NativeNoiseMode?
    private var isOpening = false
    private var activeRequestID: UUID?

    init(
        configuration: Configuration = Configuration(),
        opener: ShortcutURLOpening,
        scheduler: NoiseDwellScheduling
    ) {
        self.configuration = configuration
        self.opener = opener
        self.scheduler = scheduler
    }

    /// Accepts the manual slider or automatic hearing loop value.
    /// Values outside 0...100 are clamped before being mapped to a mode.
    func apply(level: Int) {
        precondition(Thread.isMainThread, "ShortcutsController must be used on the main thread")

        desiredLevel = min(100, max(0, level))
        desiredMode = mode(for: desiredLevel)
        reconcileDesiredMode()
    }

    func mode(for level: Int) -> NativeNoiseMode {
        level >= configuration.ancThreshold ? .noiseCancellation : .adaptive
    }

    /// Stops queued switches and invalidates callbacks/completions from the previous run.
    /// A Shortcut already handed to iOS cannot be recalled.
    func reset() {
        precondition(Thread.isMainThread, "ShortcutsController must be used on the main thread")
        cancelPendingAction()
        activeRequestID = nil
        isOpening = false
        lastLaunchedMode = nil
        lastCompletedMode = nil
        lastLaunchAt = nil
        publish(level: desiredLevel, mode: desiredMode, phase: .idle)
    }

    /// Forward app URLs here from the Expo module/app delegate integration.
    /// Returns true only for a callback generated by this controller.
    @discardableResult
    func handleCallbackURL(_ url: URL) -> Bool {
        precondition(Thread.isMainThread, "ShortcutsController must be used on the main thread")

        guard url.scheme == configuration.callbackScheme,
              url.host == "noise",
              let components = URLComponents(url: url, resolvingAgainstBaseURL: false),
              let requestID = components.queryItems?.first(where: { $0.name == "request" })?.value,
              requestID == activeRequestID?.uuidString,
              let rawMode = components.queryItems?.first(where: { $0.name == "mode" })?.value,
              let mode = NativeNoiseMode(rawValue: rawMode)
        else { return false }

        let rawLevel = components.queryItems?.first(where: { $0.name == "level" })?.value
        let level = rawLevel.flatMap(Int.init).map { min(100, max(0, $0)) } ?? desiredLevel

        switch url.path {
        case "/success":
            lastCompletedMode = mode
            lastLaunchedMode = mode
            publish(level: level, mode: mode, phase: .completed)
        case "/cancel":
            rollBackUncompletedLaunch(of: mode)
            publish(level: level, mode: mode, phase: .cancelled)
        case "/error":
            rollBackUncompletedLaunch(of: mode)
            publish(level: level, mode: mode, phase: .failed)
        default:
            return false
        }

        return true
    }

    private func reconcileDesiredMode() {
        if desiredMode == lastLaunchedMode {
            cancelPendingAction()
            return
        }

        guard !isOpening else { return }

        if let lastLaunchAt {
            let elapsed = scheduler.now.timeIntervalSince(lastLaunchAt)
            if elapsed < configuration.dwell {
                scheduleDesiredMode(after: configuration.dwell - elapsed)
                return
            }
        }

        launch(mode: desiredMode, level: desiredLevel)
    }

    private func scheduleDesiredMode(after delay: TimeInterval) {
        if pendingMode == desiredMode { return }

        cancelPendingAction()
        let scheduledMode = desiredMode
        pendingMode = scheduledMode
        let fireAt = scheduler.now.addingTimeInterval(delay)
        publish(level: desiredLevel, mode: scheduledMode, phase: .scheduled(fireAt))

        pendingAction = scheduler.schedule(after: delay) { [weak self] in
            guard let self else { return }
            self.pendingAction = nil
            self.pendingMode = nil
            guard self.desiredMode == scheduledMode else { return }
            self.reconcileDesiredMode()
        }
    }

    private func launch(mode: NativeNoiseMode, level: Int) {
        cancelPendingAction()

        let requestID = UUID()
        guard let url = shortcutURL(mode: mode, level: level, requestID: requestID) else {
            publish(level: level, mode: mode, phase: .failed)
            return
        }

        isOpening = true
        activeRequestID = requestID
        publish(level: level, mode: mode, phase: .opening)
        let requestedAt = scheduler.now

        opener.open(url) { [weak self] didOpen in
            guard let self, self.activeRequestID == requestID else { return }
            precondition(Thread.isMainThread, "Shortcut completion must return on the main thread")
            self.isOpening = false

            if didOpen {
                self.lastLaunchAt = requestedAt
                self.lastLaunchedMode = mode
                self.publish(level: level, mode: mode, phase: .launched)
            } else {
                self.publish(level: level, mode: mode, phase: .failed)
            }

            // A rejected URL should stay failed until the next sensor reading.
            // Re-enter only when the desired mode changed while this request was open;
            // otherwise a synchronous rejection recursively retries forever.
            if self.desiredMode != mode {
                self.reconcileDesiredMode()
            }
        }
    }

    private func shortcutURL(mode: NativeNoiseMode, level: Int, requestID: UUID) -> URL? {
        guard let success = callbackURL(outcome: "success", mode: mode, level: level, requestID: requestID),
              let cancel = callbackURL(outcome: "cancel", mode: mode, level: level, requestID: requestID),
              let error = callbackURL(outcome: "error", mode: mode, level: level, requestID: requestID)
        else { return nil }

        var components = URLComponents()
        components.scheme = "shortcuts"
        components.host = "x-callback-url"
        components.path = "/run-shortcut"
        components.queryItems = [
            URLQueryItem(name: "name", value: shortcutName(for: mode)),
            URLQueryItem(name: "x-success", value: success.absoluteString),
            URLQueryItem(name: "x-cancel", value: cancel.absoluteString),
            URLQueryItem(name: "x-error", value: error.absoluteString),
        ]
        return components.url
    }

    private func shortcutName(for mode: NativeNoiseMode) -> String {
        switch mode {
        case .adaptive:
            return configuration.adaptiveShortcutName
        case .noiseCancellation:
            return configuration.noiseCancellationShortcutName
        }
    }

    private func callbackURL(outcome: String, mode: NativeNoiseMode, level: Int, requestID: UUID) -> URL? {
        var components = URLComponents()
        components.scheme = configuration.callbackScheme
        components.host = "noise"
        components.path = "/\(outcome)"
        components.queryItems = [
            URLQueryItem(name: "mode", value: mode.rawValue),
            URLQueryItem(name: "level", value: String(level)),
            URLQueryItem(name: "request", value: requestID.uuidString),
        ]
        return components.url
    }

    private func rollBackUncompletedLaunch(of mode: NativeNoiseMode) {
        guard lastLaunchedMode == mode else { return }
        lastLaunchedMode = lastCompletedMode
        lastLaunchAt = nil
    }

    private func cancelPendingAction() {
        pendingAction?.cancel()
        pendingAction = nil
        pendingMode = nil
    }

    private func publish(level: Int, mode: NativeNoiseMode, phase: ShortcutRequestPhase) {
        onStateChange?(ShortcutsControllerState(level: level, mode: mode, phase: phase))
    }
}

private final class DispatchNoiseScheduledAction: NoiseScheduledAction {
    private let workItem: DispatchWorkItem

    init(workItem: DispatchWorkItem) {
        self.workItem = workItem
    }

    func cancel() {
        workItem.cancel()
    }
}

final class SystemNoiseDwellScheduler: NoiseDwellScheduling {
    var now: Date { Date() }

    func schedule(after delay: TimeInterval, _ action: @escaping () -> Void) -> NoiseScheduledAction {
        let item = DispatchWorkItem(block: action)
        DispatchQueue.main.asyncAfter(deadline: .now() + max(0, delay), execute: item)
        return DispatchNoiseScheduledAction(workItem: item)
    }
}

#if canImport(UIKit)
final class SystemShortcutURLOpener: ShortcutURLOpening {
    func open(_ url: URL, completion: @escaping (Bool) -> Void) {
        let openOnMain = {
            UIApplication.shared.open(url, options: [:]) { didOpen in
                if Thread.isMainThread {
                    completion(didOpen)
                } else {
                    DispatchQueue.main.async { completion(didOpen) }
                }
            }
        }

        if Thread.isMainThread {
            openOnMain()
        } else {
            DispatchQueue.main.async(execute: openOnMain)
        }
    }
}

extension ShortcutsController {
    convenience init(configuration: Configuration = Configuration()) {
        self.init(
            configuration: configuration,
            opener: SystemShortcutURLOpener(),
            scheduler: SystemNoiseDwellScheduler()
        )
    }
}
#endif
